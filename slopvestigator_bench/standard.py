"""The standard trial condition shared by all three evals (configs/standard.toml).

`configs/standard.toml` has a `shared` table and one table per benchmark id. A benchmark's
standard config for a budget is the shared settings, overlaid with its own table, plus the
budget and its kill timeout. `render_all()` returns every generated config as flat TOML text;
scripts/standard_configs.py writes them to configs/<prefix>-std-<budget>.toml.
"""

from __future__ import annotations

import json
import tomllib
from functools import lru_cache

from slopvestigator_bench.runtime import repo_root

# Keys that describe the condition but are not trial-config fields.
_META = {"budgets", "kill_after_min", "prefix", "judge", "judge_effort"}
# Field order in a generated file: identity, timing, agent, report, the rest.
_ORDER = ("name", "benchmark_id", "prompt", "budget_min", "timeout_min", "data_variant", "dataset_sha256",
          "effort", "min_runtime_fraction", "memory_limit", "subagents", "claude_cli_version",
          "codex_cli_version", "findings_count", "report_min_words", "report_max_words",
          "report_accept_min_words", "report_accept_max_words")


@lru_cache(maxsize=1)
def standard() -> dict:
    return tomllib.loads((repo_root() / "configs" / "standard.toml").read_text())


def benchmark_ids() -> tuple[str, ...]:
    return tuple(k for k in standard() if k != "shared")


def judge() -> tuple[str, str]:
    """The one judge model and its reasoning effort."""
    shared = standard()["shared"]
    return shared["judge"], shared["judge_effort"]


def config_name(benchmark_id: str, budget: int) -> str:
    return f"{standard()[benchmark_id]['prefix']}-std-{budget}"


def config_names(benchmark_id: str) -> tuple[str, ...]:
    return tuple(config_name(benchmark_id, b) for b in standard()["shared"]["budgets"])


def build(benchmark_id: str, budget: int) -> dict:
    shared, own = standard()["shared"], standard()[benchmark_id]
    if budget not in shared["budgets"]:
        raise ValueError(f"budget {budget} is not in the standard budgets {shared['budgets']}")
    cfg = {k: v for k, v in {**shared, **own}.items() if k not in _META}
    cfg.update(name=config_name(benchmark_id, budget), benchmark_id=benchmark_id,
               budget_min=budget, timeout_min=budget + shared["kill_after_min"])
    ordered = {k: cfg.pop(k) for k in _ORDER if k in cfg}
    return {**ordered, **dict(sorted(cfg.items()))}


def _toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(value, ensure_ascii=False)


def render(benchmark_id: str, budget: int) -> str:
    cfg = build(benchmark_id, budget)
    head = ("# Generated by scripts/standard_configs.py from configs/standard.toml; edit that file, not this one.\n"
            f"# The standard condition for {benchmark_id}, {budget} minutes.\n")
    return head + "".join(f"{k} = {_toml_value(v)}\n" for k, v in cfg.items())


def config_sha256(name: str) -> str:
    """The hash run_trial.sh records as config_sha256 for a run of configs/<name>.toml."""
    import hashlib

    return hashlib.sha256((repo_root() / "configs" / f"{name}.toml").read_bytes()).hexdigest()


def same_condition(meta: dict, name: str) -> bool:
    """Whether a run used today's configs/<name>.toml. A standard config can change under the same
    name (wiki-std-* moved from blind-v2 to wiki-v3 on 2026-10-22); a run recorded with another
    config_sha256 is a different condition. A run with no recorded hash yet is taken as current."""
    recorded = meta.get("config_sha256")
    return not recorded or recorded == config_sha256(name)


def render_all() -> dict[str, str]:
    return {config_name(b, m): render(b, m) for b in benchmark_ids() for m in standard()["shared"]["budgets"]}
