"""Docker sandbox definition: locked-down containers, corpus mounted read-only.

``default`` (image stage ``tools``) holds the corpus and runs every shell command. With
``-T agent=claude_code`` a second service, ``claude``, runs the Claude Code CLI and
inspect_swe's model bridge. Its tools are bridged back to ``default``, so the model's
commands run in a container that shares no network, filesystem or process namespace
with the bridge.

Both services:
- no network, all capabilities dropped, no privilege escalation (setuid is inert), uid 1000;
- read-only root filesystem, with size-capped tmpfs for /tmp, /home/agent and /var/tmp
  (exec, because Inspect injects its sandbox tools and agent bridge there);
- pids, memory and CPU limits, so a runaway loop can't take the host down.

``default`` also gets a writable /work: an anonymous volume, since Inspect reads
report.md with `docker cp`, which can't see tmpfs. `compose down --volumes` removes it.
Its /work/data is the corpus as built by ``build_sandbox_data`` (scans.jsonl, README.txt).
``claude`` gets an empty tmpfs /work as its working directory, so the directory Claude Code
is told it is in matches the one its bridged shell runs in.
"""

from __future__ import annotations

from pathlib import Path

from report_eval_harness.corpus import PROJECT_ROOT, Corpus, build_sandbox_data

SANDBOX_DIR = PROJECT_ROOT / "sandbox"
BUILD_DIR = PROJECT_ROOT / "build"
IMAGES = {
    "tools": "report-eval-harness-sandbox:latest",
    "claude": "report-eval-harness-claude-code:latest",
}

SERVICE_TEMPLATE = """\
  {service}:
    build:
      context: {context}
      target: {target}
    image: {image}
    init: true
    hostname: {service}
    network_mode: none
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    read_only: true
    tmpfs:
      - /tmp:size=256m,mode=1777
      - /var/tmp:size=1g,mode=1777,exec
      - /home/agent:size=256m,uid=1000,gid=1000,mode=0700
{extra_tmpfs}    pids_limit: 512
    mem_limit: 4g
    cpus: 2
    ulimits:
      core: 0
      nofile: {{soft: 4096, hard: 4096}}
    user: "1000:1000"
    working_dir: {workdir}
    command: tail -f /dev/null
"""


def _service(service: str, target: str, workdir: str, extra_tmpfs: str = "") -> str:
    return SERVICE_TEMPLATE.format(
        service=service,
        context=SANDBOX_DIR,
        target=target,
        image=IMAGES[target],
        workdir=workdir,
        extra_tmpfs=f"      - {extra_tmpfs}\n" if extra_tmpfs else "",
    )


def compose_file(corpus: Corpus, claude: bool = False) -> Path:
    """Write the compose file for ``corpus`` (plus the Claude Code service) and return it."""
    BUILD_DIR.mkdir(exist_ok=True)
    text = "# Generated by report_eval_harness.sandbox; do not edit.\nservices:\n"
    data_dir = build_sandbox_data(corpus)
    text += _service("default", "tools", "/work")
    text += f"    volumes:\n      - /work\n      - {data_dir}:/work/data:ro\n"
    if claude:
        text += _service("claude", "claude", "/work", "/work:size=16m,uid=1000,gid=1000,mode=0700")
    path = BUILD_DIR / f"compose-{corpus.name}{'-claude' if claude else ''}.yaml"
    path.write_text(text)
    return path
