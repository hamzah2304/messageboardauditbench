SCALE_HEADER = "| Score | The report… |"


def point_md(p):
    out = [f"## {p['id']} — {p['section']}",
           "", f"**Point:** {p['point']}",
           "", f"**In the human report:** “{p['report_quote']}”"]
    if p.get("supports"):
        out += ["", f"**What the data supports:** {p['supports']}"]
    if p.get("not_scored"):
        out += ["", f"**Not scored:** {p['not_scored']}"]
    return "\n".join(out)


def sheet_md(rubric_id, points, scale, instruction, credit):
    """Assemble one judge sheet. Mirrors rubric_md() in build_rubrics.py exactly."""
    ids = ", ".join(p["id"] for p in points)
    head = ["# Rubric {} — {}–{}".format(rubric_id, points[0]["id"], points[-1]["id"]),
            "",
            instruction.replace("{n}", str(len(points))),
            "",
            SCALE_HEADER,
            "| ---: | --- |"]
    head += [f"| {v} | {t} |" for v, t in scale]
    head += ["", credit, ""]
    body = "\n\n".join(point_md(p) for p in points)
    tail = ["", "---", "",
            "**Human incident report (answer key):**", "", "{{HUMAN_REPORT}}", "",
            "**Model report under evaluation:**", "", "{{MODEL_REPORT}}", "",
            "---", "",
            'Return strict JSON only: {"rubric_id": "%s", "items": ['
            ' {"id": "<one of %s>", "score": <0 to 1, one decimal place>,'
            ' "quote": "<verbatim snippet from the model report supporting the score, or empty>",'
            ' "reason": "<one sentence>"}, ... ] }' % (rubric_id, ids)]
    return "\n".join(head) + "\n" + body + "\n" + "\n".join(tail) + "\n"


