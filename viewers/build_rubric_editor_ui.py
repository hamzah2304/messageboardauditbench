#!/usr/bin/env python3
"""Build viewers/rubric_editor.html — review and edit the grading rubric in place.

The rubric the judge reads is six markdown sheets (benchmark/rubrics/rubric_1..6.md)
generated by benchmark/rubrics/build_rubrics.py. Every sheet repeats the same scale
table and the same two framing paragraphs; only the five points differ. This page
presents the shared parts ONCE as single editable objects, the 30 points individually,
and an assembled live preview of any sheet as the judge would receive it.

Beside every point sit the empirical numbers from the 76 round-3 grades
(benchmark/graded/graded_r3b*.json): mean score, share of reports scoring above 0,
share scoring 1.0, and the discrimination — the correlation between that point's score
and the report's mean over the other 29 points. Those numbers are the case for editing
or dropping a point, so they live next to the edit boxes.

Edits are stored as overrides against the generated original in
benchmark/rubric_review/rubric_edits.json (autosaved through the html-viewer's
POST /save endpoint, localStorage mirror when the server is unreachable). An unedited
field is never written, so every field reverts individually.

The scale/paragraph/point constants below mirror build_rubrics.py. The build asserts
that the assembled markdown for all six sheets is byte-identical to the committed
rubric_N.md, so drift between the two files fails the build rather than passing silently.
"""
